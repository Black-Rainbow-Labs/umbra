/**
 * Returns the broken build script.
 */
export function brokenBuildScript() {
  return [
    '// Builds the site from "my docs/input files" into "build output".',
    "// Usage: node build.mjs (from the project folder).",
    'import fs from "node:fs";',
    'import path from "node:path";',
    'import { spawnSync } from "node:child_process";',
    'import { fileURLToPath } from "node:url";',
    "",
    "const ROOT = path.dirname(fileURLToPath(import.meta.url));",
    'const INPUT_DIR = path.join(ROOT, "my docs", "input files");',
    'const TEMPLATE_FILE = path.join(ROOT, "my docs", "templates", "page template.html");',
    'const OUT_DIR = path.join(ROOT, "build output");',
    "",
    "/**",
    " * Splits a command line into words. Words are separated by spaces, and a word wrapped in single quotes may contain spaces.",
    " * @param line - the command line",
    " */",
    "function splitCommand(line) {",
    "  const words = [];",
    '  let current = "";',
    "  let quoted = false;",
    "  for (const char of line) {",
    "    if (char === \"'\") { quoted = !quoted; continue; }",
    '    if (char === " " && !quoted) { if (current) words.push(current); current = ""; continue; }',
    "    current += char;",
    "  }",
    "  if (current) words.push(current);",
    "  return words;",
    "}",
    "",
    "/**",
    " * Runs a command line from the project folder and returns its standard output.",
    " * @param line - the command line",
    " */",
    "function run(line) {",
    "  const [program, ...args] = splitCommand(line);",
    '  const result = spawnSync(program, args, { cwd: ROOT, encoding: "utf8" });',
    "  if (result.status !== 0) throw new Error(`command failed: ${line}\\n${result.stderr}`);",
    "  return result.stdout;",
    "}",
    "",
    "/**",
    " * Wraps a value in single quotes for a command line.",
    " * @param value - the value",
    " */",
    "function quote(value) {",
    "  return `'${value}'`;",
    "}",
    "",
    "/**",
    " * Turns a file name without extension into the name used for generated files.",
    " * @param name - the file name without extension",
    " */",
    "function slugify(name) {",
    '  return name.toLowerCase().replace(" ", "-").replace(/[^a-z0-9-]/g, "");',
    "}",
    "",
    "/**",
    " * Escapes the characters that matter in HTML text.",
    " * @param text - raw text",
    " */",
    "function escapeHtml(text) {",
    '  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/\\"/g, "&quot;");',
    "}",
    "",
    "/**",
    " * Lists every file under a folder, in the order the file system returns them.",
    " * @param dir - the folder",
    " */",
    "function listFiles(dir) {",
    "  const found = [];",
    "  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {",
    "    const full = path.join(dir, entry.name);",
    "    if (entry.isDirectory()) found.push(...listFiles(full));",
    "    else found.push(full);",
    "  }",
    "  return found;",
    "}",
    "",
    "/**",
    " * Builds the output for one input file and returns its manifest entry.",
    " * @param file - the absolute path of the input file",
    " */",
    "function buildFile(file) {",
    "  const extension = path.extname(file).toLowerCase();",
    "  const base = path.basename(file, path.extname(file));",
    "  let output;",
    '  if (extension === ".md") {',
    '    output = path.join(OUT_DIR, "pages", slugify(base) + ".html");',
    "    run(`node tools/render-md.mjs ${quote(file)} ${quote(output)}`);",
    '  } else if (extension === ".csv") {',
    '    output = path.join(OUT_DIR, "tables", slugify(base) + ".html");',
    "    run(`node tools/csv-table.mjs ${quote(file)} ${quote(output)}`);",
    "  } else {",
    '    output = path.join(OUT_DIR, "raw", path.basename(file));',
    "    fs.copyFileSync(file, output);",
    "  }",
    "  const sha256 = run(`node tools/checksum.mjs ${output}`).trim();",
    "  return { source: path.relative(ROOT, file), output: path.relative(ROOT, output), sha256, base };",
    "}",
    "",
    "/**",
    " * Writes index.html from the page template, with a link to every page and table.",
    " * @param entries - the manifest entries",
    " */",
    "function writeIndex(entries) {",
    "  const linked = entries.filter((entry) => entry.output.includes(\"pages\") || entry.output.includes(\"tables\"));",
    "  const links = linked.map((entry) => `<li><a href=\"${path.relative(OUT_DIR, path.join(ROOT, entry.output))}\">${escapeHtml(entry.base)}</a></li>`);",
    '  const template = fs.readFileSync(TEMPLATE_FILE, "utf8");',
    '  const html = template.replace("{{title}}", "Site index").replace("{{links}}", links.join("\\n"));',
    '  fs.writeFileSync(path.join(OUT_DIR, "index.html"), html);',
    "}",
    "",
    "/**",
    " * Builds the whole site.",
    " */",
    "function main() {",
    "  fs.mkdirSync(OUT_DIR);",
    '  for (const folder of ["pages", "tables", "raw"]) fs.mkdirSync(path.join(OUT_DIR, folder));',
    "  const entries = listFiles(INPUT_DIR).map(buildFile);",
    "  writeIndex(entries);",
    "  const manifest = entries.map(({ source, output, sha256 }) => ({ source, output, sha256 }));",
    '  fs.writeFileSync(path.join(OUT_DIR, "manifest.json"), JSON.stringify(manifest, null, 2) + "\\n");',
    "}",
    "",
    "main();",
    "",
  ].join("\n");
}
